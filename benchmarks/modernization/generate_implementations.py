from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "transaction_corpus.json"
MERIT_OUT = HERE / "merit" / "src" / "main.mrt"
JAVA_OUT = HERE / "java" / "ModernizationBenchmark.java"

RESULT_CODES = {
    "committed": 0,
    "invalid_amount": 1,
    "same_account": 2,
    "wrong_debit_account": 3,
    "wrong_credit_account": 4,
    "duplicate_or_out_of_order": 5,
    "insufficient_funds": 6,
    "credit_overflow": 7,
}


def money(minor: int) -> str:
    sign = "-" if minor < 0 else ""
    value = abs(int(minor))
    return f"{sign}{value // 100}.{value % 100:02d}"


def load_corpus() -> dict:
    data = json.loads(CORPUS.read_text(encoding="utf-8"))
    if data.get("schema") != "merit-modernization-transaction-v1":
        raise ValueError("unsupported corpus")
    return data


def generate_merit(data: dict) -> str:
    lines = [
        "// GENERATED from ../transaction_corpus.json by generate_implementations.py.",
        "// Do not edit this file directly.",
        "module modernization_benchmark",
        "",
        "capability allocate;",
        "",
        "decimal USD(18, 2, half_even);",
        "bounded AccountNumber(u64, 1, 999999999999);",
        "bounded Sequence(u64, 0, 9999999999999999999);",
        "",
        "struct Account {",
        "    id: AccountNumber;",
        "    balance: USD;",
        "    last_sequence: Sequence;",
        "}",
        "",
        "fn find_account(borrow accounts: Vec<Account>, id: AccountNumber) -> i64 {",
        "    var index: i64 = 0;",
        "    while (index < vec_len<Account>(accounts)) {",
        "        let account: Account = vec_get<Account>(accounts, index);",
        "        if (account.id == id) { return index; }",
        "        index = checked_add(index, 1);",
        "    }",
        "    return -1;",
        "}",
        "",
        "fn apply_transaction(",
        "    borrow_mut accounts: Vec<Account>,",
        "    debit_id: AccountNumber,",
        "    credit_id: AccountNumber,",
        "    amount: USD,",
        "    sequence: Sequence",
        ") -> i32 {",
        "    if (amount <= 0.00) { return 1; }",
        "    if (debit_id == credit_id) { return 2; }",
        "    let debit_index: i64 = find_account(accounts, debit_id);",
        "    if (debit_index < 0) { return 3; }",
        "    let credit_index: i64 = find_account(accounts, credit_id);",
        "    if (credit_index < 0) { return 4; }",
        "",
        "    let debit: Account = vec_get<Account>(accounts, debit_index);",
        "    let credit: Account = vec_get<Account>(accounts, credit_index);",
        "    if (sequence <= debit.last_sequence) { return 5; }",
        "    if (sequence <= credit.last_sequence) { return 5; }",
        "    if (debit.balance < amount) { return 6; }",
        f"    if (credit.balance > {money(data['max_balance_minor'])} - amount) {{ return 7; }}",
        "",
        "    var updated_debit: Account = debit;",
        "    updated_debit.balance = checked_sub(updated_debit.balance, amount);",
        "    updated_debit.last_sequence = sequence;",
        "    var updated_credit: Account = credit;",
        "    updated_credit.balance = checked_add(updated_credit.balance, amount);",
        "    updated_credit.last_sequence = sequence;",
        "    vec_set<Account>(accounts, debit_index, updated_debit);",
        "    vec_set<Account>(accounts, credit_index, updated_credit);",
        "    return 0;",
        "}",
        "",
        "fn main() -> i32 {",
        "    with capability allocate {",
        "        let allocator: Allocator = system_allocator();",
        f"        var accounts: Vec<Account> = vec_new<Account>(allocator, {len(data['accounts'])});",
    ]
    for account in data["accounts"]:
        lines.extend([
            "        vec_push<Account>(accounts, Account {",
            f"            id: {account['id']},",
            f"            balance: {money(account['balance_minor'])},",
            f"            last_sequence: {account['last_sequence']}",
            "        });",
        ])
    lines.extend(["", "        print(-900);"])
    for tx in data["transactions"]:
        lines.append(
            "        print(apply_transaction(accounts, "
            f"{tx['debit']}, {tx['credit']}, {money(tx['amount_minor'])}, {tx['sequence']}));"
        )
    lines.extend([
        "        print(-901);",
        "        var index: i64 = 0;",
        "        while (index < vec_len<Account>(accounts)) {",
        "            let account: Account = vec_get<Account>(accounts, index);",
        "            print(account.id);",
        "            print(account.balance);",
        "            print(account.last_sequence);",
        "            index = checked_add(index, 1);",
        "        }",
        "        drop(accounts);",
        "    }",
        "    return 0;",
        "}",
        "",
    ])
    return "\n".join(lines)


def generate_java(data: dict) -> str:
    account_rows = ",\n".join(
        f'        new Account({a["id"]}L, new BigDecimal("{money(a["balance_minor"])}"), {a["last_sequence"]}L)'
        for a in data["accounts"]
    )
    tx_lines = "\n".join(
        "        System.out.println(apply(accounts, "
        f'{tx["debit"]}L, {tx["credit"]}L, new BigDecimal("{money(tx["amount_minor"])}"), {tx["sequence"]}L));'
        for tx in data["transactions"]
    )
    maximum = money(data["max_balance_minor"])
    return f'''// GENERATED from ../transaction_corpus.json by generate_implementations.py.
// Do not edit this file directly.
import java.math.BigDecimal;

public final class ModernizationBenchmark {{
    private static final BigDecimal ZERO = new BigDecimal("0.00");
    private static final BigDecimal MAX_BALANCE = new BigDecimal("{maximum}");

    private static final class Account {{
        final long id;
        BigDecimal balance;
        long lastSequence;

        Account(long id, BigDecimal balance, long lastSequence) {{
            this.id = id;
            this.balance = balance;
            this.lastSequence = lastSequence;
        }}
    }}

    private static int find(Account[] accounts, long id) {{
        for (int i = 0; i < accounts.length; i++) {{
            if (accounts[i].id == id) return i;
        }}
        return -1;
    }}

    private static int apply(Account[] accounts, long debitId, long creditId, BigDecimal amount, long sequence) {{
        if (amount.compareTo(ZERO) <= 0) return 1;
        if (debitId == creditId) return 2;
        int debitIndex = find(accounts, debitId);
        if (debitIndex < 0) return 3;
        int creditIndex = find(accounts, creditId);
        if (creditIndex < 0) return 4;

        Account debit = accounts[debitIndex];
        Account credit = accounts[creditIndex];
        if (sequence <= debit.lastSequence || sequence <= credit.lastSequence) return 5;
        if (debit.balance.compareTo(amount) < 0) return 6;
        if (credit.balance.compareTo(MAX_BALANCE.subtract(amount)) > 0) return 7;

        debit.balance = debit.balance.subtract(amount);
        credit.balance = credit.balance.add(amount);
        debit.lastSequence = sequence;
        credit.lastSequence = sequence;
        return 0;
    }}

    public static void main(String[] args) {{
        Account[] accounts = new Account[] {{
{account_rows}
        }};
        System.out.println(-900);
{tx_lines}
        System.out.println(-901);
        for (Account account : accounts) {{
            System.out.println(account.id);
            System.out.println(account.balance.setScale(2).toPlainString());
            System.out.println(account.lastSequence);
        }}
    }}
}}
'''


def generated() -> dict[Path, str]:
    data = load_corpus()
    return {MERIT_OUT: generate_merit(data), JAVA_OUT: generate_java(data)}


def main() -> int:
    for path, content in generated().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(path.relative_to(HERE))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
