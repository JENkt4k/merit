from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "transaction_corpus.json"
CSHARP_OUT = HERE / "csharp" / "ModernizationBenchmark.cs"


def money(minor: int) -> str:
    sign = "-" if minor < 0 else ""
    value = abs(int(minor))
    return f"{sign}{value // 100}.{value % 100:02d}"


def load_corpus() -> dict:
    data = json.loads(CORPUS.read_text(encoding="utf-8"))
    if data.get("schema") != "merit-modernization-transaction-v1":
        raise ValueError("unsupported corpus")
    return data


def generate(data: dict) -> str:
    accounts = ",\n".join(
        f"            new Account({a['id']}L, {money(a['balance_minor'])}m, {a['last_sequence']}L)"
        for a in data["accounts"]
    )
    transactions = "\n".join(
        f"        Console.WriteLine(Apply(accounts, {t['debit']}L, {t['credit']}L, {money(t['amount_minor'])}m, {t['sequence']}L));"
        for t in data["transactions"]
    )
    maximum = money(data["max_balance_minor"])
    return f'''// GENERATED from ../transaction_corpus.json by generate_csharp.py.
// Do not edit this file directly.
using System;
using System.Globalization;

internal static class ModernizationBenchmark
{{
    private const decimal MaxBalance = {maximum}m;

    private sealed class Account
    {{
        internal readonly long Id;
        internal decimal Balance;
        internal long LastSequence;

        internal Account(long id, decimal balance, long lastSequence)
        {{
            Id = id;
            Balance = balance;
            LastSequence = lastSequence;
        }}
    }}

    private static int Find(Account[] accounts, long id)
    {{
        for (var i = 0; i < accounts.Length; i++)
            if (accounts[i].Id == id) return i;
        return -1;
    }}

    private static int Apply(Account[] accounts, long debitId, long creditId, decimal amount, long sequence)
    {{
        if (amount <= 0.00m) return 1;
        if (debitId == creditId) return 2;
        var debitIndex = Find(accounts, debitId);
        if (debitIndex < 0) return 3;
        var creditIndex = Find(accounts, creditId);
        if (creditIndex < 0) return 4;

        var debit = accounts[debitIndex];
        var credit = accounts[creditIndex];
        if (sequence <= debit.LastSequence || sequence <= credit.LastSequence) return 5;
        if (debit.Balance < amount) return 6;
        if (credit.Balance > MaxBalance - amount) return 7;

        checked
        {{
            debit.Balance -= amount;
            credit.Balance += amount;
        }}
        debit.LastSequence = sequence;
        credit.LastSequence = sequence;
        return 0;
    }}

    public static int Main()
    {{
        CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
        var accounts = new Account[]
        {{
{accounts}
        }};
        Console.WriteLine(-900);
{transactions}
        Console.WriteLine(-901);
        foreach (var account in accounts)
        {{
            Console.WriteLine(account.Id);
            Console.WriteLine(account.Balance.ToString("F2", CultureInfo.InvariantCulture));
            Console.WriteLine(account.LastSequence);
        }}
        return 0;
    }}
}}
'''


def main() -> int:
    CSHARP_OUT.parent.mkdir(parents=True, exist_ok=True)
    CSHARP_OUT.write_text(generate(load_corpus()), encoding="utf-8")
    print(CSHARP_OUT.relative_to(HERE))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
